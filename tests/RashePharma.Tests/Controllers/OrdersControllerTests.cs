    [Fact]
    public async Task Create_ShouldReturnOk_WhenCartAndAddressAreValid()
    {
        // Arrange
        var setup = await CreateOrderSetupAsync();

        await CreateCartItemAsync(
            setup.UserId,
            setup.VariantId,
            quantity: 2,
            unitPrice: 100m);

        var dto = new CreateOrderDto
        {
            AddressId = setup.AddressId
        };

        SetBearerToken(setup.Token);

        // Act
        var response = await _client.PostAsJsonAsync(
            "/api/orders",
            dto);

        // Assert
        Assert.Equal(
            HttpStatusCode.OK,
            response.StatusCode);

        var order =
            await response.Content
                .ReadFromJsonAsync<OrderDetailsDto>();

        Assert.NotNull(order);

        Assert.True(order.Id > 0);
        Assert.False(
            string.IsNullOrWhiteSpace(order.OrderNumber));

        Assert.StartsWith(
            "ORD-",
            order.OrderNumber);

        Assert.Equal("INR", order.Currency);
        Assert.Equal("Pending", order.Status);

        Assert.Equal(
            200m,
            order.TotalAmount);

        Assert.Equal(
            "123 Order Street",
            order.ShippingAddressLine1);

        Assert.Equal(
            "Bengaluru",
            order.ShippingCity);

        Assert.Equal(
            "Karnataka",
            order.ShippingState);

        var item = Assert.Single(order.Items);

        Assert.Equal(
            setup.VariantId,
            item.ProductVariantId);

        Assert.Equal(
            2,
            item.Quantity);

        Assert.Equal(
            100m,
            item.UnitPrice);
    }


