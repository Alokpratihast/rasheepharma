    private async Task<(int UserId, string Token)> CreateAuthenticatedUserAsync()
    {
        await SeedRoleAsync();

        var email =
            $"order-auth-{Guid.NewGuid():N}@example.com";

        var registerDto = new RegisterDto
        {
            FirstName = "Order",
            LastName = "TestUser",
            Email = email,
            PhoneNumber = "+91-9876543210",
            Country = "India",
            Password = "password123"
        };

        var registerResponse = await _client.PostAsJsonAsync(
            "/api/auth/register",
            registerDto);

        Assert.Equal(
            HttpStatusCode.OK,
            registerResponse.StatusCode);

        var registerResult =
            await registerResponse.Content
                .ReadFromJsonAsync<AuthResponseDto>();

        Assert.NotNull(registerResult);
        Assert.True(registerResult.UserId > 0);


        // Login to get a fresh JWT.
        var loginDto = new LoginDto
        {
            Email = email,
            Password = "password123"
        };

        var loginResponse = await _client.PostAsJsonAsync(
            "/api/auth/login",
            loginDto);

        Assert.Equal(
            HttpStatusCode.OK,
            loginResponse.StatusCode);

        var loginResult =
            await loginResponse.Content
                .ReadFromJsonAsync<AuthResponseDto>();

        Assert.NotNull(loginResult);
        Assert.False(
            string.IsNullOrWhiteSpace(loginResult.Token));

        return (
            loginResult.UserId,
            loginResult.Token
        );
    }


    private void SetBearerToken(string token)
    {
        _client.DefaultRequestHeaders.Authorization =
            new AuthenticationHeaderValue(
                "Bearer",
                token);
    }


    private void ClearBearerToken()
    {
        _client.DefaultRequestHeaders.Authorization = null;
    }


    // =========================================================
    // ROLE
    // =========================================================

    private async Task SeedRoleAsync()
    {
        using var scope = _factory.Services.CreateScope();

        var db = scope.ServiceProvider
            .GetRequiredService<ApplicationDbContext>();

        if (!db.Roles.Any(r => r.Id == 2))
        {
            db.Roles.Add(new Role
            {
                Id = 2,
                Name = "Customer"
            });

            await db.SaveChangesAsync();
        }
    }


    private async Task<string> CreateAdminTokenAsync()
    {
        using var scope = _factory.Services.CreateScope();

        var db = scope.ServiceProvider
            .GetRequiredService<ApplicationDbContext>();


        // Make sure Admin role exists.
        var adminRole = await db.Roles
            .FirstOrDefaultAsync(r => r.Id == 1);

        if (adminRole == null)
        {
            adminRole = new Role
            {
                Id = 1,
                Name = "Admin"
            };

            db.Roles.Add(adminRole);

            await db.SaveChangesAsync();
        }


        var email =
            $"admin-{Guid.NewGuid():N}@example.com";

        var admin = new User
        {
            FirstName = "Test",
            LastName = "Admin",
            Email = email,
            PhoneNumber = "+91-9999999999",
            Country = "India",
            RoleId = adminRole.Id,
            IsActive = true
        };

        var passwordHasher = new PasswordHasher<User>();

        admin.PasswordHash =
            passwordHasher.HashPassword(
                admin,
                "adminPassword123");

        db.Users.Add(admin);

        await db.SaveChangesAsync();


        // Login through the real API so that the JWT is
        // generated by the actual JwtTokenService.
        var loginDto = new LoginDto
        {
            Email = email,
            Password = "adminPassword123"
        };

        var loginResponse = await _client.PostAsJsonAsync(
            "/api/auth/login",
            loginDto);

        Assert.Equal(
            HttpStatusCode.OK,
            loginResponse.StatusCode);

        var result =
            await loginResponse.Content
                .ReadFromJsonAsync<AuthResponseDto>();

        Assert.NotNull(result);
        Assert.False(
            string.IsNullOrWhiteSpace(result.Token));

        return result.Token;
    }


