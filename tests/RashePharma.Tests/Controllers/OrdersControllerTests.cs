    // =========================================================
    // ORDER
    // =========================================================

    private async Task<int> CreateOrderAsync(
        int userId,
        int productVariantId,
        decimal unitPrice = 100m,
        int quantity = 2)
    {
        using var scope = _factory.Services.CreateScope();

        var db = scope.ServiceProvider
            .GetRequiredService<ApplicationDbContext>();

        var order = new Order
        {
            UserId = userId,
            OrderNumber = $"ORD-TEST-{Guid.NewGuid():N}",
            TotalAmount = unitPrice * quantity,
            Currency = "INR",
            Status = "Pending",

            ShippingAddressLine1 = "123 Order Street",
            ShippingAddressLine2 = "Test Area",
            ShippingCity = "Bengaluru",
            ShippingState = "Karnataka",
            ShippingPostalCode = "560001",
            ShippingCountry = "India"
        };

        var variant = await db.ProductVariants
            .Include(v => v.Product)
            .FirstAsync(v => v.Id == productVariantId);

        var orderItem = new OrderItem
        {
            OrderId = order.Id,
            ProductVariantId = productVariantId,
            ProductName = variant.Product.Name,
            Strength = variant.Strength,
            PackSize = variant.PackSize,
            Quantity = quantity,
            UnitPrice = unitPrice
        };

        order.Items.Add(orderItem);

        db.Orders.Add(order);

        await db.SaveChangesAsync();

        return order.Id;
    }


    private async Task<(
        int UserId,
        int AddressId,
        int VariantId,
        string Token)> CreateOrderSetupAsync()
    {
        var user = await CreateAuthenticatedUserAsync();

        var addressId =
            await CreateAddressAsync(user.UserId);

        var categoryId =
            await CreateCategoryAsync();

        var productId =
            await CreateProductAsync(categoryId);

        var variantId =
            await CreateProductVariantAsync(productId);

        return (
            user.UserId,
            addressId,
            variantId,
            user.Token
        );
    }


